function summary(productId: string) {
  const product = products.find((item) => item.id === productId)

  if (!product) {
    throw new Error(`Unknown catalog product: ${productId}`)
  }

  return {
    id: product.id,
    title: product.title,
    subtitle: product.subtitle,
    image: product.image,
    price: product.price,
    originalPrice: product.originalPrice,
    stock: product.stock,
    soldPercentage: product.soldPercentage,
  }
}

